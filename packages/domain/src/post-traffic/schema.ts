import { PostId, WorkspaceId } from "@feeblo/id";
import * as S from "effect/Schema";

/**
 * One value of a breakdown dimension and how many views it accounts for.
 *
 * `value` is a closed vocabulary produced at ingest (`country` an ISO code, the
 * rest the parser's names), not free text from the client.
 */
export const PostViewDimensionCount = S.Struct({
  value: S.String,
  views: S.Finite,
});

export type TPostViewDimensionCount = S.Schema.Type<
  typeof PostViewDimensionCount
>;

/**
 * The dashboard's read for one post.
 *
 * `views` is all time and comes from the counter; the window is the last 30
 * days of events, which is the retention-independent part of the answer. The
 * two are deliberately different questions: "how many ever" is the number a
 * customer reads, "from where lately" is what the breakdown answers.
 */
export const PostTrafficPayload = S.Struct({
  organizationId: WorkspaceId.schema,
  postId: PostId.schema,
});

export type TPostTrafficPayload = S.Schema.Type<typeof PostTrafficPayload>;

export const PostTrafficWindow = S.Struct({
  views: S.Finite,
  countries: S.Array(PostViewDimensionCount),
  devices: S.Array(PostViewDimensionCount),
  browsers: S.Array(PostViewDimensionCount),
  os: S.Array(PostViewDimensionCount),
});

export const PostTraffic = S.Struct({
  postId: S.String,
  /** All time. */
  views: S.Finite,
  last30Days: PostTrafficWindow,
});

export type TPostTraffic = S.Schema.Type<typeof PostTraffic>;

/**
 * The sidebar's headline number. It is a separate operation from
 * `GetPostTraffic` so opening a post does not read four breakdowns the reader
 * has not asked for; the analytics tab owns that read.
 */
export const PostViewCount = S.Struct({
  postId: S.String,
  views: S.Finite,
});

export type TPostViewCount = S.Schema.Type<typeof PostViewCount>;

/**
 * What the browser could tell about its own form factor.
 *
 * The hint exists for the one case a user agent cannot answer: iPadOS 13+
 * reports a Macintosh agent, so a Macintosh UA alone is a Mac or an iPad. The
 * client sends what it can prove from touch points; omitting the hint means
 * "ambiguous", and the server then refuses to guess desktop.
 */
export const PostViewDeviceHint = S.Literals(["desktop", "mobile", "tablet"]);

export type TPostViewDeviceHint = S.Schema.Type<typeof PostViewDeviceHint>;

/** The device stored on a view; "unknown" is a real answer, not a failure. */
export const PostViewDevice = S.Literals([
  "desktop",
  "mobile",
  "tablet",
  "unknown",
]);

/**
 * What the board's same-origin relay forwards.
 *
 * `id` is generated by the client so a retried beacon is free: the insert is
 * `on conflict do nothing`, and only a row that actually landed increments the
 * counter. It is validated as the v4 UUID the board generates, so the storage
 * key is not arbitrary caller text. Nothing here identifies a visitor.
 */
export const RecordPostViewInput = S.Struct({
  id: S.String.check(S.isUUID(4)),
  postId: S.String.check(S.isMinLength(1), S.isMaxLength(128)),
  /**
   * The device hint the browser could prove about itself. Carried in the body
   * because it is a browser fact, not a request header.
   */
  deviceHint: S.optional(PostViewDeviceHint),
  /**
   * The browser's agent, forwarded by the relay. Carried in the body rather
   * than a header because some server runtimes (Cloudflare Workers) overwrite
   * `User-Agent` on outbound requests. A direct caller may omit it.
   */
  userAgent: S.optional(S.String.check(S.isMaxLength(1024))),
  /**
   * The edge's country header, forwarded by the relay. The handler trusts it
   * only when the request arrived through the trusted relay/proxy boundary;
   * a direct caller's value is ignored.
   */
  country: S.optional(S.String.check(S.isMaxLength(8))),
});

/**
 * The ingest endpoint answers this for every accepted request, including one it
 * silently discards. It never says whether the post exists or is public.
 */
export const RecordPostViewAccepted = S.Struct({
  accepted: S.Boolean,
});
